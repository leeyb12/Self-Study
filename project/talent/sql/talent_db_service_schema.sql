-- 1. 기존 테이블 삭제
 DROP TABLE APPLICATIONS;
 DROP TABLE SERVICES;
 DROP TABLE USERS;

-- 2. 회원 테이블 생성
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) UNIQUE NOT NULL,
    PASSWORD VARCHAR2(200) NOT NULL,
    NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'ROLE_USER', -- ROLE_USER, ROLE_ADMIN
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. 재능 서비스 테이블 생성
CREATE TABLE SERVICES (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID     NUMBER, -- 등록자 ID
    TITLE       VARCHAR2(200) NOT NULL,
    DESCRIPTION CLOB,
    PRICE       NUMBER DEFAULT 0,
    IMAGE_URL   VARCHAR2(500),
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SERVICE_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

-- 4. 서비스 신청 내역 테이블 생성
CREATE TABLE APPLICATIONS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERVICE_ID     NUMBER NOT NULL,
    USER_ID        NUMBER, -- 신청자 회원 ID
    APPLICANT_NAME VARCHAR2(100) NOT NULL,
    STATUS         VARCHAR2(50) DEFAULT 'PENDING',
    APPLIED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_APP_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SERVICES(ID) ON DELETE CASCADE,
    CONSTRAINT FK_APP_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

